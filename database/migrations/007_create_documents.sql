CREATE TABLE documents (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  tracking_no VARCHAR(30) NOT NULL UNIQUE,
  title VARCHAR(255) NOT NULL,
  document_type_id INT UNSIGNED NOT NULL,
  reference_no VARCHAR(100) NULL,
  description TEXT NULL,
  priority ENUM('normal','urgent') NOT NULL DEFAULT 'normal',
  confidentiality ENUM('normal','confidential') NOT NULL DEFAULT 'normal',
  format ENUM('physical','digital','both') NOT NULL DEFAULT 'physical',
  pages SMALLINT UNSIGNED NULL,
  origin_department_id INT UNSIGNED NOT NULL,
  created_by INT UNSIGNED NOT NULL,
  current_department_id INT UNSIGNED NOT NULL,
  current_holder_id INT UNSIGNED NULL,
  status ENUM('draft','in_transit','received','completed','cancelled') NOT NULL DEFAULT 'draft',
  completed_at DATETIME NULL,
  completed_by INT UNSIGNED NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NULL ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_documents_type FOREIGN KEY (document_type_id) REFERENCES document_types(id),
  CONSTRAINT fk_documents_origin_department FOREIGN KEY (origin_department_id) REFERENCES departments(id),
  CONSTRAINT fk_documents_created_by FOREIGN KEY (created_by) REFERENCES users(id),
  CONSTRAINT fk_documents_current_department FOREIGN KEY (current_department_id) REFERENCES departments(id),
  CONSTRAINT fk_documents_current_holder FOREIGN KEY (current_holder_id) REFERENCES users(id),
  CONSTRAINT fk_documents_completed_by FOREIGN KEY (completed_by) REFERENCES users(id),
  INDEX idx_documents_status (status),
  INDEX idx_documents_current (current_department_id, status),
  INDEX idx_documents_created_at (created_at),
  FULLTEXT INDEX ft_documents_search (title, description, reference_no)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
