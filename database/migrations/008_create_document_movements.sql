-- Permanent movement history: rows are never deleted.
CREATE TABLE document_movements (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  document_id INT UNSIGNED NOT NULL,
  action ENUM('send','forward','return') NOT NULL,
  from_department_id INT UNSIGNED NOT NULL,
  from_user_id INT UNSIGNED NOT NULL,
  to_department_id INT UNSIGNED NOT NULL,
  to_user_id INT UNSIGNED NULL,
  note VARCHAR(500) NOT NULL,
  due_date DATE NULL,
  status ENUM('in_transit','received','recalled') NOT NULL DEFAULT 'in_transit',
  sent_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  received_by INT UNSIGNED NULL,
  received_at DATETIME NULL,
  receive_method ENUM('click','qr','bulk') NULL,
  receipt_note VARCHAR(500) NULL,
  recalled_by INT UNSIGNED NULL,
  recalled_at DATETIME NULL,
  recall_reason VARCHAR(500) NULL,
  last_alert_at DATETIME NULL,
  CONSTRAINT fk_movements_document FOREIGN KEY (document_id) REFERENCES documents(id),
  CONSTRAINT fk_movements_from_department FOREIGN KEY (from_department_id) REFERENCES departments(id),
  CONSTRAINT fk_movements_from_user FOREIGN KEY (from_user_id) REFERENCES users(id),
  CONSTRAINT fk_movements_to_department FOREIGN KEY (to_department_id) REFERENCES departments(id),
  CONSTRAINT fk_movements_to_user FOREIGN KEY (to_user_id) REFERENCES users(id),
  CONSTRAINT fk_movements_received_by FOREIGN KEY (received_by) REFERENCES users(id),
  CONSTRAINT fk_movements_recalled_by FOREIGN KEY (recalled_by) REFERENCES users(id),
  INDEX idx_movements_document (document_id, sent_at),
  INDEX idx_movements_to (to_department_id, status),
  INDEX idx_movements_from (from_department_id, status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
